export function getCountryByCode(code: string): CountryInfo {
  const found = SUPPORTED_COUNTRIES.find((c) => c.code.toUpperCase() === (code || '').toUpperCase());
  return found || SUPPORTED_COUNTRIES[0];
}

export function getCountryByDialCode(dialCode: string): CountryInfo {
  const clean = dialCode.trim();
  const found = SUPPORTED_COUNTRIES.find((c) => c.dialCode === clean);
  return found || SUPPORTED_COUNTRIES[0];
}

/**
 * Format currency centrally based on account / business settings.
 * Ensures numbers are properly localized without converting values.
 */
export function formatMoney(
  amount: number,
  currencyCodeOrSymbol: string = 'MT',
  options?: { hideDecimalsIfWhole?: boolean; showPlus?: boolean },
  lang: SupportedLanguage = 'pt'
): string {
  const num = typeof amount === 'number' && !isNaN(amount) ? amount : 0;
  const isNegative = num < 0;
  const absNum = Math.abs(num);

  const raw = (currencyCodeOrSymbol || 'MT').trim();
  const country = SUPPORTED_COUNTRIES.find(
    (c) =>
      c.currencyCode.toUpperCase() === raw.toUpperCase() ||
      c.currencySymbol.toUpperCase() === raw.toUpperCase()
  );

  const symbol = country ? country.currencySymbol : raw;
  const isPrefix = country ? country.symbolPosition === 'prefix' : ['$', 'R$', '€', '£', 'R'].includes(symbol);

  let locale = 'pt-MZ';
  if (lang === 'pt-BR') locale = 'pt-BR';
  else if (lang === 'en') locale = 'en-US';
  else if (lang === 'es') locale = 'es-ES';
  else if (lang === 'fr') locale = 'fr-FR';
  else if (country?.code === 'US' || country?.code === 'ZA') locale = 'en-US';

  const hasDecimals = absNum % 1 !== 0;
  const formattedNumber = absNum.toLocaleString(locale, {
    minimumFractionDigits: hasDecimals ? 2 : 0,
    maximumFractionDigits: 2
  });

  let prefixSign = '';
  if (isNegative) {
    prefixSign = '-';
  } else if (options?.showPlus && num > 0) {
    prefixSign = '+';
  }

  if (isPrefix) {
    const separator = symbol.length > 1 ? ' ' : '';
    return `${prefixSign}${symbol}${separator}${formattedNumber}`;
  } else {
    return `${prefixSign}${formattedNumber} ${symbol}`;
  }
}

/**
 * Date and time formatter localized by active language
 */
export function formatLocalDate(isoOrDate?: string | Date | number, lang: SupportedLanguage = 'pt'): string {
  if (!isoOrDate) return '';
  const d = new Date(isoOrDate);
  if (isNaN(d.getTime())) return '';

  let locale = 'pt-MZ';
  if (lang === 'pt-BR') locale = 'pt-BR';
  else if (lang === 'en') locale = 'en-US';
  else if (lang === 'es') locale = 'es-ES';
  else if (lang === 'fr') locale = 'fr-FR';

  return d.toLocaleDateString(locale, {
    day: '2-digit',
    month: '2-digit',
    year: 'numeric'
  });
}

export function formatLocalDateTime(isoOrDate?: string | Date | number, lang: SupportedLanguage = 'pt'): string {
  if (!isoOrDate) return '';
  const d = new Date(isoOrDate);
  if (isNaN(d.getTime())) return '';

  let locale = 'pt-MZ';
  if (lang === 'pt-BR') locale = 'pt-BR';
  else if (lang === 'en') locale = 'en-US';
  else if (lang === 'es') locale = 'es-ES';
  else if (lang === 'fr') locale = 'fr-FR';

  return d.toLocaleString(locale, {
    day: '2-digit',
    month: '2-digit',
    year: 'numeric',
    hour: '2-digit',
    minute: '2-digit'
  });
}

