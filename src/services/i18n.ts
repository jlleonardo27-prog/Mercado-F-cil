/**
 * Robust translate helper with intelligent fallbacks:
 * 1. Target language dictionary
 * 2. If pt-BR, fall back to pt
 * 3. Fall back to pt
 * 4. Fall back to key itself
 */
export function translate(
  lang: SupportedLanguage = 'pt',
  key: string,
  params?: Record<string, string | number>
): string {
  const dict = translations[lang] || translations.pt;
  let text = dict[key];

  if (text === undefined) {
    if (lang === 'pt-BR' && translations.pt[key]) {
      text = translations.pt[key];
    } else if (translations.pt[key]) {
      text = translations.pt[key];
    } else {
      text = key;
    }
  }

  if (params) {
    for (const [pKey, pVal] of Object.entries(params)) {
      text = text.replace(new RegExp(`{${pKey}}`, 'g'), String(pVal));
    }
  }

  return text;
}
